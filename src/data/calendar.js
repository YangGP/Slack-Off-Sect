/**
 * 历法与节气。
 *
 * 时间换算（1 天 = 2 秒真实时间，照猫国的节奏）：
 *   1 节气 = 15 天 = 30 秒
 *   1 季   = 6 节气 = 90 天 = 3 分钟
 *   1 年   = 4 季 = 24 节气 = 360 天 = 12 分钟
 *
 * 对照猫国：它 100 天一季、一天 2 秒 → 3.3 分钟一季、13.3 分钟一年；
 * 我们受 24 节气约束（24 ÷ 4 × 15 = 90 天一季），所以是 90 天，节奏几乎一样。
 *
 * 因为一节气只有 30 秒，节气变化**不写纪事**（否则纪事会被历法刷满），
 * 只进右栏历法面板与状态行；入季 / 跨年才写一条纪事。
 *
 * 季节会真的影响产出：`ratio` 里的百分比直接乘进对应资源的产出
 * （与建筑 / 修真的 ratio 是同一层乘区，见 engine.recompute）。
 */
export const CALENDAR = {
  /**
   * 一天多少现实秒。照猫国定成 2 秒（猫国：100 天一季 × 2 秒/天 ≈ 3.3 分钟一季），
   * 我们一季 90 天（24 节气 ÷ 4 季 × 15 天），所以一季 3 分钟、一节气 30 秒、一年 12 分钟。
   * 想再快/再慢就只改这一个数：季长 = 90 × DAY_SECONDS 秒。
   */
  DAY_SECONDS: 2,
  DAYS_PER_TERM: 15,
}

